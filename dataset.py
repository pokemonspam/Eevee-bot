def get_pokemon_type_emojis(pokemon_name: str) -> list:
    """
    Looks up a Pokémon's types and returns a list of corresponding Discord type emojis.
    Example: get_pokemon_type_emojis("Bulbasaur") -> [":grass:", ":poison:"]
    """
    clean_name = pokemon_name.strip().lower()
    raw_types = POKEMON_TYPES.get(clean_name, "")
    
    if not raw_types:
        return []
        
    type_list = raw_types.split()
    emojis = [TYPE_EMOJIS[t] for t in type_list if t in TYPE_EMOJIS]
    return emojis

